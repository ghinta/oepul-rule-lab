"""Build the Run Explorer data from published metadata, without host paths."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs/assets/runs.js"


def render() -> str:
    records = []
    dates = []
    # New local experiments are ignored. Only versioned publications belong on
    # the public site, even when this command runs on a developer's machine.
    tracked = subprocess.check_output(
        ["git", "ls-files", "runs/*/run.json"], cwd=ROOT, text=True
    ).splitlines()
    for name in tracked:
        path = ROOT / name
        run = json.loads(path.read_text())
        if run["status"] != "finalized":
            continue
        metrics = run["metrics"]
        sheets = [source["name"] for source in run["sources"]
                  if source["name"].startswith(run["measure"] + "_")]
        if len(sheets) != 1:
            raise ValueError(f"Expected one measure leaflet: {name}")
        records.append([
            run["measure"], run["model"]["model"],
            run["model"].get("reasoning_effort", "not recorded"),
            run["run_id"], sheets[0], metrics["structured_rule_count"],
            metrics["source_reference_count"], metrics["coverage_item_count"],
            metrics["generated_test_count"], metrics["profile_change_proposal_count"],
            metrics["profile_paths_added"],
            metrics["grounding_valid"] and metrics["technical_validation_exit_code"] == 0,
        ])
        dates.append(run["finalized_at"])
    records.sort(key=lambda row: (row[0], row[1], row[3]))
    return (
        "// Generated by tools/build_explorer.py from versioned run metadata.\n"
        + "const RUN_SNAPSHOT = " + json.dumps({"latestFinalizedAt": max(dates)}, sort_keys=True) + ";\n"
        + "const RAW_RUNS = " + json.dumps(records, ensure_ascii=False, separators=(",", ":")) + ";\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != content:
            parser.error("Explorer data is stale; run python3 tools/build_explorer.py")
    else:
        OUTPUT.write_text(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
